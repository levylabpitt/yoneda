#!/usr/bin/env python3
"""THE genome. One specification, two dialects.

cell.sql and cell.pg.sql are GENERATED FROM THIS FILE. Do not hand-edit them:
they must agree column for column, because a laptop instance is copied into the
Timescale hub without conversion, and two files maintained by hand drift the
first time somebody is in a hurry. Today they drifted twice in one afternoon.

Nothing domain-specific lives here. This is the substrate: one `cell` table
holding cells of every dimension, a derived `edge` endpoint index maintained by
trigger, and an `active` view where the latest outcome wins.

    python genome.py --write     regenerate both .sql files
    python genome.py --check     exit 1 if either committed file is stale
    genome.ddl("sqlite")         the DDL as a string
"""

# --- the one place the schema is stated -------------------------------------
# (name, sqlite type, postgres type, comment)
COLUMNS = [
    ("i",  "TEXT PRIMARY KEY", "uuid PRIMARY KEY",
     "identity: content-hash (immutable cells) OR uuidv7 (authored cells)"),
    ("j",  "TEXT NOT NULL", "jsonb NOT NULL",
     "payload JSON: {kind, faces:{role -> cell id}, data:{...}}"),
    ("b",  "TEXT", "text",
     "authoring big-bang id (NULL => content-addressed / definitional)"),
    ("t",  "REAL", "double precision",
     "event time, unix seconds (NULL => content-addressed)"),
    ("rt", "REAL", "double precision",
     "record time, unix seconds: when this cell was asserted"),
]

INDEXES = [
    ("cell_t_idx",   "t"),
    ("cell_rt_idx",  "rt"),
    ("cell_b_t_idx", "b, t DESC"),
]

HEADER = """Yoneda uniform-cell genome (see ../design-federation-2026-07-29.md).
ONE table of cells of every dimension. A relation is a cell that carries face pointers;
this is the globular-set presentation of the (inf,1)-category: cells + source/target maps.
Replaces the two-table o/r genome. Nothing here is domain-specific.

GENERATED FROM genome.py -- DO NOT EDIT THIS FILE.
Edit genome.py and run `python genome.py --write`. Both dialects come from one
specification precisely so they cannot drift; `python genome.py --check` fails if a
committed file is stale.

WHY t IS UNIX SECONDS AND NOT t_universe. Do not "fix" this.

t_universe(now()) is about 4.354e17, and the ulp of a double there is exactly 64
seconds: two cells less than a minute apart would be the same number. At unix
magnitude (~1.79e9) the ulp is 238 nanoseconds. So the epoch is applied as a
read-time coordinate transform and never stored. Orderings and differences are
invariant under a constant shift, so storing unix loses nothing; the epoch matters
only for the absolute display coordinate, and anything computing it should use an
exact type (Python decimal.Decimal, Postgres NUMERIC) rather than a float.

TWO times, not one. An event happening and an event being written down are different
facts, and in a laboratory notebook they are routinely days apart. Measured over
20,699 pages of the Levy lab corpus: 58% were created after the day they describe,
median lag one day, 87% within a week, and 3.5% were created BEFORE the date they
name, because the author laid out session pages in advance. One column cannot hold
both, and collapsing them silently converts a write-up timestamp into a measurement
timestamp.

  t   when the thing happened             (event time)
  rt  when this cell asserted it happened (record time)

THE IDENTITY IS THE HASH, ALL OF IT. This column was `uuid` in Postgres, and a
Postgres uuid is sixteen bytes, so a content id was a sha256 cut in half with six
more bits overwritten to make the version and variant nibbles well-formed. That
left an identifier that is no longer the hash: you could not check it by hashing
the content and comparing strings, you had to remember and re-apply the
truncation rule. 122 bits is collision-free at any size this will reach, so the
argument for it was never safety, only that it fit a column type.

So the column is text and it holds the whole 64-hex digest. A content id can now
be verified by anyone with the content and a sha256 implementation, which is the
entire point of content addressing. Authored cells still carry a uuidv7, which is
a genuine uuid and stays one; the column holds both because it is text.

AND TIME IS INDEXED. Time is the only key every source emits without anyone agreeing
a convention: a OneNote page, an Asana task, a Timescale reading and a file mtime all
carry one and share no identifier, so joining across them is a temporal-coincidence
argument. Measured on one person's records, 63 Asana events against 1,287 notebook
pages with nothing in common but time: median gap to the nearest page 22.2 h against
a null of 50.5 h, p = 0.007. An unindexed axis is not an axis."""


def _comment(text):
    return "\n".join(("-- " + line).rstrip() for line in text.split("\n"))


def ddl(dialect):
    """The genome for 'sqlite' or 'postgres', as one string."""
    if dialect not in ("sqlite", "postgres"):
        raise ValueError("unknown dialect %r" % (dialect,))
    pg = dialect == "postgres"
    idx = 2 if pg else 1
    C = "cell.cell" if pg else "cell"
    E = "cell.edge" if pg else "edge"
    ID = "text" if pg else "TEXT"
    TXT = "text" if pg else "TEXT"

    out = [_comment(HEADER), ""]
    if pg:
        out += ["-- Installed in schema `cell`, additive: leaves public.o/r untouched.",
                "-- Reverse with: DROP SCHEMA cell CASCADE;",
                "",
                "CREATE SCHEMA IF NOT EXISTS cell;",
                ""]

    # The comma belongs to the column, not to the comment. Appended after the
    # comment it lands inside it, which reads as valid SQL and is not.
    w = max(len(c[idx]) for c in COLUMNS) + 3
    rows = []
    for n, c in enumerate(COLUMNS):
        decl = c[idx] + ("," if n < len(COLUMNS) - 1 else "")
        rows.append(("  %-3s %-*s-- %s" % (c[0], w, decl, c[3])).rstrip())
    out += ["CREATE TABLE IF NOT EXISTS %s(" % C, "\n".join(rows), ");", ""]

    for name, cols in INDEXES:
        out.append("CREATE INDEX IF NOT EXISTS %s ON %s(%s);" % (name, C, cols))
    out.append("")

    if pg:
        out += [
            "-- On TimescaleDB, partition on event time, which is why this stack is on",
            "-- Timescale at all. Left commented because content-addressed cells carry NULL t",
            "-- and cannot be partitioned; enable it on an instance whose cells all have a time.",
            "--   SELECT create_hypertable('cell.cell', 't', chunk_time_interval => 604800,",
            "--                            if_not_exists => TRUE, migrate_data => TRUE);",
            "",
        ]

    out += [
        "-- Derived endpoint index: one row per (cell, role, endpoint). An ACCELERATOR, not truth;",
        "-- fully rebuildable from cell.j, maintained by trigger, so Hom(-,X) stays a B-tree lookup.",
        "CREATE TABLE IF NOT EXISTS %s(" % E,
        "  cell %s NOT NULL," % ID,
        "  role %s NOT NULL," % TXT,
        "  endpoint %s NOT NULL," % ID,
        "  PRIMARY KEY(cell, role, endpoint)",
        ");",
        "CREATE INDEX IF NOT EXISTS edge_endpoint ON %s(endpoint);" % E,
        "",
        "-- faces in j.faces (a role->id object) become edge rows automatically on insert.",
    ]

    if pg:
        dollar = "$" + "$"
        out += [
            "CREATE OR REPLACE FUNCTION cell.faces_ai() RETURNS trigger AS " + dollar,
            "BEGIN",
            "  INSERT INTO cell.edge(cell, role, endpoint)",
            "  SELECT NEW.i, kv.key, kv.value #>> '{}'",
            "  FROM jsonb_each(COALESCE(NEW.j->'faces', '{}'::jsonb)) kv",
            "  ON CONFLICT DO NOTHING;",
            "  RETURN NEW;",
            "END " + dollar + " LANGUAGE plpgsql;",
            "",
            "DROP TRIGGER IF EXISTS cell_faces_ai ON cell.cell;",
            "CREATE TRIGGER cell_faces_ai AFTER INSERT ON cell.cell",
            "  FOR EACH ROW EXECUTE FUNCTION cell.faces_ai();",
            "",
        ]
    else:
        out += [
            "CREATE TRIGGER IF NOT EXISTS cell_faces_ai AFTER INSERT ON cell BEGIN",
            "  INSERT OR IGNORE INTO edge(cell, role, endpoint)",
            "  SELECT NEW.i, je.key, je.value",
            "  FROM json_each(coalesce(json_extract(NEW.j,'$.faces'),'{}')) je;",
            "END;",
            "",
        ]

    out += [
        "-- active: latest outcome wins. A cell is active unless a cell of kind 'outcome' pointing",
        "-- at it (role 'of') most recently says data.status = 'retracted'. Applies to ANY cell.",
    ]
    if pg:
        out += [
            "CREATE OR REPLACE VIEW cell.active AS",
            "SELECT c.* FROM cell.cell c",
            "WHERE COALESCE((",
            "  SELECT o.j->'data'->>'status'",
            "  FROM cell.cell o JOIN cell.edge e ON e.cell=o.i AND e.role='of' AND e.endpoint=c.i",
            "  WHERE o.j->>'kind' = 'outcome'",
            "  ORDER BY o.t DESC NULLS LAST LIMIT 1",
            "), 'active') <> 'retracted';",
        ]
    else:
        out += [
            "CREATE VIEW IF NOT EXISTS active AS",
            "SELECT c.* FROM cell c",
            "WHERE coalesce((",
            "  SELECT json_extract(o.j,'$.data.status')",
            "  FROM cell o JOIN edge e ON e.cell = o.i AND e.role='of' AND e.endpoint = c.i",
            "  WHERE json_extract(o.j,'$.kind') = 'outcome'",
            "  ORDER BY o.t DESC, o.rowid DESC LIMIT 1   -- rowid breaks ties for coincident cells",
            "), 'active') <> 'retracted';",
        ]
    return "\n".join(out) + "\n"


# Where each dialect lands. The site copies are generated too: a hand-kept copy
# under site/public is exactly how the fourth divergent genome got there.
# Paths are relative to the repo root.
FILES = {
    "sqlite":   ["cell/cell.sql",    "site/public/cell.sql"],
    # stem-cell/ keeps the onboarding material (genesis.md, BOOT.md, the watcher,
    # docker-compose.yml) and its compose file mounts the genome beside itself.
    "postgres": ["cell/cell.pg.sql", "site/public/cell.pg.sql", "stem-cell/cell.pg.sql"],
}

if __name__ == "__main__":
    import sys, os
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    mode = sys.argv[1] if len(sys.argv) > 1 else "--check"
    stale = []
    for dialect, paths in FILES.items():
        want = ddl(dialect)
        for rel in paths:
            path = os.path.join(root, rel.replace("/", os.sep))
            have = open(path, encoding="utf8").read() if os.path.exists(path) else None
            if mode == "--write":
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf8", newline="\n") as f:
                    f.write(want)
                print("wrote " + rel)
            elif want != have:
                stale.append(rel)
    if mode == "--check":
        if stale:
            print("STALE, run `python genome.py --write`: " + ", ".join(stale))
            sys.exit(1)
        print("all generated files match genome.py")
